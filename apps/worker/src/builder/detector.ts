import fs from 'fs';
import path from 'path';

export interface DetectionResult {
  hasDockerfile: boolean;
  dockerfilePath: string;
  projectType: 'dockerfile' | 'nodejs' | 'python' | 'golang' | 'static' | 'unknown';
  generatedDockerfile?: string;
}

export function detectProject(repoDir: string, defaultPort = 3000): DetectionResult {
  // 1. Check for standard Dockerfile
  const candidates = [
    'Dockerfile',
    'dockerfile',
    'docker/Dockerfile',
    'deploy/Dockerfile',
  ];

  for (const candidate of candidates) {
    const fullPath = path.join(repoDir, candidate);
    if (fs.existsSync(fullPath)) {
      return {
        hasDockerfile: true,
        dockerfilePath: fullPath,
        projectType: 'dockerfile',
      };
    }
  }

  // 2. Check for Node.js
  if (fs.existsSync(path.join(repoDir, 'package.json'))) {
    const pkg = JSON.parse(fs.readFileSync(path.join(repoDir, 'package.json'), 'utf-8'));
    const startScript = pkg.scripts?.start ? 'npm start' : 'node index.js';

    const generated = `
# Generated by DeployForge Node.js Buildpack
FROM node:20-alpine AS runner
WORKDIR /app
ENV NODE_ENV=production
ENV PORT=${defaultPort}

# Non-root security user
RUN addgroup -S nodejs -g 1001 && adduser -S nodeuser -u 1001 -G nodejs

COPY package*.json ./
RUN npm ci --only=production --ignore-scripts || npm install --production

COPY --chown=nodeuser:nodejs . .
USER nodeuser

EXPOSE ${defaultPort}
CMD [${startScript.split(' ').map((s: string) => `"${s}"`).join(', ')}]
`.trim();

    return {
      hasDockerfile: false,
      dockerfilePath: path.join(repoDir, 'Dockerfile'),
      projectType: 'nodejs',
      generatedDockerfile: generated,
    };
  }

  // 3. Check for Python
  if (
    fs.existsSync(path.join(repoDir, 'requirements.txt')) ||
    fs.existsSync(path.join(repoDir, 'Pipfile')) ||
    fs.existsSync(path.join(repoDir, 'pyproject.toml'))
  ) {
    const generated = `
# Generated by DeployForge Python Buildpack
FROM python:3.11-slim AS runner
WORKDIR /app
ENV PYTHONDONTWRITEBYTECODE=1
ENV PYTHONUNBUFFERED=1
ENV PORT=${defaultPort}

RUN groupadd -g 1001 pygroup && useradd -u 1001 -g pygroup pyuser

COPY requirements*.txt ./
RUN pip install --no-cache-dir -r requirements.txt || true

COPY --chown=pyuser:pygroup . .
USER pyuser

EXPOSE ${defaultPort}
CMD ["python", "app.py"]
`.trim();

    return {
      hasDockerfile: false,
      dockerfilePath: path.join(repoDir, 'Dockerfile'),
      projectType: 'python',
      generatedDockerfile: generated,
    };
  }

  // 4. Check for Go
  if (fs.existsSync(path.join(repoDir, 'go.mod'))) {
    const generated = `
# Generated by DeployForge Go Buildpack
FROM golang:1.22-alpine AS builder
WORKDIR /src
COPY go.* ./
RUN go mod download
COPY . .
RUN CGO_ENABLED=0 GOOS=linux go build -o /app/server .

FROM alpine:3.19 AS runner
WORKDIR /app
ENV PORT=${defaultPort}
RUN adduser -D -u 1001 gouser
COPY --from=builder /app/server /app/server
USER gouser
EXPOSE ${defaultPort}
CMD ["/app/server"]
`.trim();

    return {
      hasDockerfile: false,
      dockerfilePath: path.join(repoDir, 'Dockerfile'),
      projectType: 'golang',
      generatedDockerfile: generated,
    };
  }

  // 5. Check for Static HTML
  if (fs.existsSync(path.join(repoDir, 'index.html'))) {
    const generated = `
# Generated by DeployForge Static Site Buildpack
FROM nginx:alpine AS runner
COPY . /usr/share/nginx/html
EXPOSE 80
CMD ["nginx", "-g", "daemon off;"]
`.trim();

    return {
      hasDockerfile: false,
      dockerfilePath: path.join(repoDir, 'Dockerfile'),
      projectType: 'static',
      generatedDockerfile: generated,
    };
  }

  return {
    hasDockerfile: false,
    dockerfilePath: path.join(repoDir, 'Dockerfile'),
    projectType: 'unknown',
  };
}
